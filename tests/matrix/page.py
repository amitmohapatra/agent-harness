"""The feature x framework page of the docs, written from the matrix's own tables:
``python -m tests.matrix.page`` (``make matrix-page``) writes ``docs/matrix.md``, and
``tests/unit/test_docs.py`` fails when the committed page is not what this writes — so the page
cannot say a framework has a feature the tests do not run, or miss one they do.

What it reads is what ``make matrix`` turns into tests (``generate.CELLS``): a cell that applies
is a test there, one that does not is no test and carries its reason. The results of a run are
``build/matrix.md`` (``report.py``); this page is what is tested, run by run the same.
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from collections.abc import Sequence
from pathlib import Path
from typing import Final

from tests.matrix.generate import CELLS, Cell
from tests.matrix.model import ADAPTERS, MODES, NA, Bug, Gap
from tests.matrix.report import _row, _rule

PAGE: Final = Path(__file__).resolve().parents[2] / "docs" / "matrix.md"
#: The frameworks as the docs name them, in the matrix's order, with their pages.
NAMES: Final = {
    "react": ("ReAct", "frameworks/react.md"),
    "middleware": (
        "middleware() on create_agent",
        "frameworks/react.md#middleware-on-your-own-graph",
    ),
    "function": ("function", "frameworks/functions.md"),
    "langgraph": ("LangGraph", "frameworks/langgraph.md"),
    "deepagents": ("Deep Agents", "frameworks/deepagents.md"),
    "openai_agents": ("OpenAI Agents", "frameworks/openai-agents.md"),
    "claude": ("Claude Agent SDK", "frameworks/claude-agent-sdk.md"),
    "kimi": ("Kimi Code (ACP)", "frameworks/kimi.md"),
}


#: What a framework's column cannot show, said under the tables: the limits its tests pin.
LIMITS: Final = {
    "kimi": [
        "ACP shows no hook before a tool runs: a call Kimi does not ask permission for (its "
        "reads, in its default mode) runs under Kimi's own policy, and is recorded after.",
        "A sub-agent's (and a swarm member's) own calls are not shown over ACP, only those it "
        "asks permission for, which are governed; its child run holds its task and answer.",
        "Spending: tokens from Kimi's usage log (every agent's), toward the budget; dollars only "
        "with the follow-up that reads the gateway's log (a `max_cost` budget does not see "
        "them yet).",
        "Sandbox (F73 runs the harness's sandbox tools; `kimi(sandbox=sandbox())` is Kimi's "
        "own): its commands and writes run in the sandbox, its reads (`Read`, `Glob`, `Grep`) "
        "read the host: reads are not isolated.",
        "Swarms run their members concurrently, as Kimi does "
        "(`KIMI_CODE_AGENT_SWARM_MAX_CONCURRENCY` in `env` caps it).",
    ],
}


class Reasons:
    """Why a cell does not apply, numbered in the order the page first gives each."""

    def __init__(self) -> None:
        self.numbers: dict[str, int] = {}

    def __call__(self, reason: str) -> int:
        return self.numbers.setdefault(reason, len(self.numbers) + 1)


def _cell(cells: Sequence[Cell], reasons: Reasons) -> str:
    """One feature on one framework, Way 1: how many tests run it, and where it does not apply."""
    tests = [c for c in cells if not isinstance(c.note, NA)]
    not_here = sorted({reasons(c.note.reason) for c in cells if isinstance(c.note, NA)})
    held = sorted({c.note.id for c in tests if isinstance(c.note, Gap | Bug)})
    if not tests:
        return f"no ({', '.join(map(str, not_here))})"
    said = f"{'partly' if not_here else 'yes'} {len(tests)}"
    if not_here:
        said += f" ({', '.join(map(str, not_here))})"
    if held:
        said += f", waits on {'/'.join(held)}"
    return said


def render() -> str:
    reasons = Reasons()
    way1: dict[tuple[str, str], list[Cell]] = defaultdict(list)
    way2: dict[str, list[Cell]] = defaultdict(list)
    titles: dict[str, str] = {}
    for cell in CELLS:
        titles.setdefault(cell.feature.id, cell.feature.title)
        if cell.way == "way1":
            way1[(cell.feature.id, cell.adapter)].append(cell)
        elif cell.way == "way2" and cell.adapter == "function" and cell.mode == "run":
            way2[cell.feature.id].append(cell)
    out = [
        "# Feature x framework",
        "",
        "<!-- Generated by `make matrix-page` (python -m tests.matrix.page) from the test matrix:",
        "     do not edit; tests/unit/test_docs.py fails when this page and the matrix differ. -->",
        "",
        "Which feature works with which framework, as the test matrix (`tests/matrix`) tests it.",
        "This page is written from the matrix's own tables and a test fails when the two differ,",
        "so it cannot claim what is not tested. `make matrix` runs every test counted here (CI",
        "runs it on every change; `build/matrix.md` is the result of a run).",
        "",
        f"A test is one feature on one framework, in one of the {len(MODES)} ways a run is driven",
        f"({', '.join(f'`{m}`' for m in MODES)}), under one selection of what is on (everything,",
        "nothing, the feature's needs alone, each of them turned off with `without=`).",
        "",
        "- **yes n**: n tests run the feature on that framework, every mode",
        "- **partly n (k)**: n tests; the modes left out do not apply, for reason k below",
        "- **no (k)**: the feature does not apply to that framework, for reason k below",
        "- **waits on G..**: the tests run and must fail until the gap or bug named closes",
        "",
        "## Way 1: the harness runs your agent (`h.wrap`)",
        "",
        _row(["feature", *(f"[{NAMES[a][0]}]({NAMES[a][1]})" for a in ADAPTERS)]),
        _rule(len(ADAPTERS) + 1),
    ]
    for feature, title in titles.items():
        row = [_cell(way1[(feature, a)], reasons) for a in ADAPTERS]
        out.append(_row([f"{feature} {title}", *row]))
    out += [
        "",
        "## Way 2: your framework runs the agent, your code calls the blocks",
        "",
        "A block is the same call whatever the framework, so the matrix runs each once, as plain",
        "code; [the recipes](README.md#way-2-pluggable-blocks-your-framework-our-pieces) show it inside each framework.",
        "",
        _row(["feature", "block"]),
        _rule(2),
    ]
    for feature, title in titles.items():
        cells = way2[feature]
        if not cells:
            continue
        out.append(_row([f"{feature} {title}", _cell(cells, reasons)]))
    for adapter, said in LIMITS.items():
        out += ["", f"### What the {NAMES[adapter][0]} column does not show", ""]
        out += [f"- {line}" for line in said]
    out += ["", "## Reasons", ""]
    out += [f"{n}. {reason}" for reason, n in reasons.numbers.items()]
    out.append("")
    return "\n".join(out)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m tests.matrix.page", description=__doc__)
    parser.add_argument("--out", type=Path, default=PAGE)
    args = parser.parse_args(argv)
    args.out.write_text(render())
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
